package io.github.dishan18.books.manga.source.local

import io.github.dishan18.books.manga.data.SeriesStatus
import io.github.dishan18.books.manga.source.SourceType
import io.github.dishan18.books.manga.source.api.Listing
import io.github.dishan18.books.manga.source.api.MangaSource
import io.github.dishan18.books.manga.source.api.SeriesDetails
import io.github.dishan18.books.manga.source.api.SeriesPage
import io.github.dishan18.books.manga.source.api.SourceChapter
import io.github.dishan18.books.manga.source.api.SourceError
import io.github.dishan18.books.manga.source.api.SourceException
import io.github.dishan18.books.manga.source.api.SourcePage
import io.github.dishan18.books.manga.source.api.SourceSeries
import io.github.dishan18.books.manga.util.NaturalOrder
import io.github.dishan18.books.manga.util.isImageName
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File
import java.net.URLDecoder
import java.net.URLEncoder
import java.util.zip.ZipFile

/** Metadata stored next to imported files as `series.json`. */
@Serializable
data class LocalSeriesInfo(val title: String, val author: String? = null, val description: String? = null)

/**
 * Manga imported onto this device. Layout under [root]:
 * `<seriesKey>/series.json`, `<seriesKey>/cover.jpg`, and one CBZ/ZIP file or image folder per chapter.
 */
class LocalSource(private val root: File) : MangaSource {
    override val id = ID
    override val name = "On this device"
    override val type = SourceType.LOCAL
    override val isOnline = false
    override val supportsLatest = false

    fun seriesDir(seriesKey: String): File {
        val dir = File(root, seriesKey)
        // Keys are generated by the importer, but never let one escape the root.
        require(dir.canonicalPath.startsWith(root.canonicalPath + File.separator)) { "Invalid series key" }
        return dir
    }

    fun readInfo(seriesKey: String): LocalSeriesInfo? =
        File(seriesDir(seriesKey), INFO_FILE).takeIf { it.isFile }
            ?.let { runCatching { json.decodeFromString(LocalSeriesInfo.serializer(), it.readText()) }.getOrNull() }

    fun writeInfo(seriesKey: String, info: LocalSeriesInfo) {
        File(seriesDir(seriesKey), INFO_FILE).writeText(json.encodeToString(LocalSeriesInfo.serializer(), info))
    }

    fun coverFile(seriesKey: String) = File(seriesDir(seriesKey), COVER_FILE)

    override suspend fun browse(listing: Listing, page: Int): SeriesPage = search("", page)

    override suspend fun search(query: String, page: Int): SeriesPage = withContext(Dispatchers.IO) {
        val all = root.listFiles { file -> file.isDirectory }.orEmpty()
            .mapNotNull { dir -> readInfo(dir.name)?.let { dir.name to it } }
            .filter { (_, info) -> query.isBlank() || info.title.contains(query.trim(), ignoreCase = true) }
            .sortedWith(compareBy(NaturalOrder) { it.second.title })
        val pageItems = all.drop((page - 1) * PAGE_SIZE).take(PAGE_SIZE)
        SeriesPage(
            items = pageItems.map { (key, info) -> SourceSeries(key, info.title, coverUri(key), info.author) },
            hasNextPage = page * PAGE_SIZE < all.size,
        )
    }

    override suspend fun details(seriesKey: String): SeriesDetails = withContext(Dispatchers.IO) {
        val info = readInfo(seriesKey) ?: throw SourceException(SourceError.NotFound)
        SeriesDetails(
            key = seriesKey,
            title = info.title,
            author = info.author,
            artist = null,
            description = info.description,
            coverUrl = coverUri(seriesKey),
            status = SeriesStatus.UNKNOWN,
            genres = emptyList(),
            webUrl = null,
        )
    }

    override suspend fun chapters(seriesKey: String): List<SourceChapter> = withContext(Dispatchers.IO) {
        val dir = seriesDir(seriesKey)
        if (!dir.isDirectory) throw SourceException(SourceError.NotFound)
        chapterFiles(dir).map { file ->
            SourceChapter(
                key = file.name,
                name = file.nameWithoutExtensionIfArchive(),
                number = CHAPTER_NUMBER.find(file.nameWithoutExtensionIfArchive())?.groupValues?.get(1)?.toFloatOrNull(),
                volume = null,
                scanlator = null,
                uploadedAt = file.lastModified(),
                pageCount = null,
            )
        }
    }

    override suspend fun pages(seriesKey: String, chapterKey: String): List<SourcePage> = withContext(Dispatchers.IO) {
        val chapter = chapterFile(seriesKey, chapterKey)
        imageEntries(chapter).mapIndexed { index, entry -> SourcePage(index, encode(seriesKey, chapterKey, entry)) }
            .also { if (it.isEmpty()) throw SourceException(SourceError.Other("This chapter has no images")) }
    }

    override suspend fun fetchPage(page: SourcePage, destination: File, onProgress: (Long, Long) -> Unit) =
        withContext(Dispatchers.IO) {
            val (seriesKey, chapterKey, entry) = decode(page.url)
            val chapter = chapterFile(seriesKey, chapterKey)
            destination.parentFile?.mkdirs()
            val temp = File(destination.parentFile, destination.name + ".part")
            try {
                if (chapter.isDirectory) {
                    val image = File(chapter, entry)
                    require(image.canonicalFile.parentFile == chapter.canonicalFile) { "Invalid page" }
                    image.inputStream().use { input -> temp.outputStream().use { input.copyTo(it) } }
                } else {
                    ZipFile(chapter).use { zip ->
                        val zipEntry = zip.getEntry(entry) ?: throw SourceException(SourceError.NotFound)
                        if (zipEntry.size > MAX_ENTRY_BYTES) throw SourceException(SourceError.Other("Image too large"))
                        zip.getInputStream(zipEntry).use { input -> temp.outputStream().use { input.copyTo(it) } }
                    }
                }
                if (!temp.renameTo(destination)) {
                    temp.copyTo(destination, overwrite = true)
                    temp.delete()
                }
                onProgress(destination.length(), destination.length())
            } catch (e: Exception) {
                temp.delete()
                throw e
            }
        }

    private fun coverUri(seriesKey: String) = coverFile(seriesKey).takeIf { it.isFile }?.toURI()?.toString()

    private fun chapterFile(seriesKey: String, chapterKey: String): File {
        val dir = seriesDir(seriesKey)
        val file = File(dir, chapterKey)
        require(file.canonicalFile.parentFile == dir.canonicalFile) { "Invalid chapter key" }
        if (!file.exists()) throw SourceException(SourceError.NotFound)
        return file
    }

    companion object {
        const val ID = "local"
        const val INFO_FILE = "series.json"
        const val COVER_FILE = "cover.jpg"
        private const val PAGE_SIZE = 60
        private const val MAX_ENTRY_BYTES = 100L * 1024 * 1024
        private val CHAPTER_NUMBER = Regex("""(?i)(?:ch(?:apter)?\.?\s*)?(\d+(?:\.\d+)?)(?!.*\d)""")
        private val json = Json { ignoreUnknownKeys = true; prettyPrint = true }

        fun isArchive(name: String) = name.substringAfterLast('.', "").lowercase() in setOf("cbz", "zip")

        /** Chapters of a series folder: archives and image folders, in natural order. */
        fun chapterFiles(dir: File): List<File> =
            dir.listFiles { file -> (file.isFile && isArchive(file.name)) || (file.isDirectory && !file.name.startsWith(".")) }
                .orEmpty()
                .sortedWith(compareBy(NaturalOrder) { it.name })

        /** Image entry names of an archive or folder chapter, in natural order. */
        fun imageEntries(chapter: File): List<String> =
            if (chapter.isDirectory) {
                chapter.list().orEmpty().filter { isImageName(it) }.sortedWith(NaturalOrder)
            } else {
                ZipFile(chapter).use { zip ->
                    zip.entries().asSequence().filter { !it.isDirectory && isImageName(it.name) }
                        .map { it.name }.toList().sortedWith(NaturalOrder)
                }
            }

        private fun File.nameWithoutExtensionIfArchive() = if (isFile && isArchive(name)) nameWithoutExtension else name

        private fun encode(vararg parts: String) = parts.joinToString("/") { URLEncoder.encode(it, Charsets.UTF_8) }

        private fun decode(url: String): Triple<String, String, String> {
            val parts = url.split('/').map { URLDecoder.decode(it, Charsets.UTF_8) }
            require(parts.size == 3) { "Invalid local page" }
            return Triple(parts[0], parts[1], parts[2])
        }
    }
}
